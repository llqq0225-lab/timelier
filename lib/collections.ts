export function guessCollection(name: string): string | null {
  // 리차드밀은 모델번호(RM011 → RM11, RM35-01 → RM35)
  const rm = name.match(/RM\s?-?(\d{2,3})/i);
  if (/리[차처]드\s?밀/.test(name) && rm) return `RM${rm[1].replace(/^0(\d\d)$/, '$1')}`;
  for (const [re, col] of RULES) if (re.test(name)) return col;
  return null;
}
